'use strict';
// K2-04 T7 (C1): tools/release-version-check.cjs reads the package version from Cargo.lock by the package NAME. Renaming the crate
// (abito-island -> koda-island) must not leave it reading nothing: a release tag is validated with it, so it has to work with the
// old name and with the new one, on a lock file in either shape. No workflow calls it, so only this check can catch a stale name.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { expected } = require('../tools/release-version-check.cjs');

let passed = 0;
const test = (_name, fn) => { fn(); passed += 1; };

function layout(lockName, { version = '0.1.0', channel = '' } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'koda-rvc-'));
  fs.writeFileSync(path.join(dir, 'Cargo.toml'), `[package]\nname = "x"\nversion = "${version}"\n`);
  fs.writeFileSync(path.join(dir, 'tauri.conf.json'), JSON.stringify({ version }));
  fs.writeFileSync(path.join(dir, 'RELEASE_CHANNEL'), `${channel}\n`);
  fs.writeFileSync(path.join(dir, 'Cargo.lock'),
    `# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "aho-corasick"\nversion = "1.1.3"\n\n[[package]]\nname = "${lockName}"\nversion = "${version}"\ndependencies = [\n "tauri",\n]\n`);
  return dir;
}

test('the current package name (abito-island) is read from Cargo.lock', () => {
  const e = expected(layout('abito-island'));
  assert.deepEqual(e.problems, []);
  assert.equal(e.tag, 'v0.1.0');
});

test('the renamed package (koda-island) is read from Cargo.lock too', () => {
  const e = expected(layout('koda-island', { version: '0.2.0', channel: 'preview.3' }));
  assert.deepEqual(e.problems, [], 'a renamed crate must not make the version "disagree"');
  assert.equal(e.tag, 'v0.2.0-preview.3');
  assert.equal(e.shown, '0.2.0 (preview 3)');
});

test('a lock whose app package has an unrelated name is still reported as disagreeing, never silently accepted', () => {
  const e = expected(layout('some-other-crate'));
  assert.equal(e.problems.length, 1);
  assert.match(e.problems[0], /versions disagree/);
});

test('the real checkout agrees with itself', () => {
  assert.deepEqual(expected().problems, []);
});

console.log(`release-version-check-check: ${passed} passed`);
